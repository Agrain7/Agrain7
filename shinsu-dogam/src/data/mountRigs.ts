const GLOBAL: Record<MotionKind, (a: RigAnim, t: number) => GlobalPose> = {
  quad: (a, t) => {
    switch (a) {
      case 'idle': return { y: 0.007 * sin(t) };
      case 'run': return { y: -0.022 * Math.abs(sin(t, 0.1)), r: 1.6 * sin(t, 0.3) };
      case 'fly': return { r: -5 };
      case 'atk': { const k = atkK(t); return { x: 0.045 * k, r: 3 * k }; }
    }
  },
  bird: (a, t) => {
    switch (a) {
      case 'idle': return { y: 0.008 * sin(t) };
      case 'run': return { y: -0.012 * Math.abs(sin(t)) };
      case 'fly': return { y: -0.035 * sin(t, -0.12), r: 2 * sin(t, 0.1) };
      case 'atk': { const k = atkK(t); return { x: 0.035 * k, r: -4 * k }; }
    }
  },
  serpent: (a, t) => {
    switch (a) {
      case 'idle': return { y: 0.008 * sin(t) };
      case 'run': return { y: -0.015 * Math.abs(sin(t)), r: 1.2 * sin(t, 0.3) };
      case 'fly': return { y: 0.025 * sin(t), r: 2.5 * sin(t, 0.25) };
      case 'atk': { const k = atkK(t); return { x: 0.04 * k, r: 2 * k }; }
    }
  },
  shell: (a, t) => {
    switch (a) {
      case 'idle': return { y: 0.004 * sin(t) };
      case 'run': return { y: -0.01 * Math.abs(sin(t)), r: 1.2 * sin(t, 0.3) };
      case 'fly': return { y: -0.01 * Math.abs(sin(t)), r: 1.2 * sin(t, 0.3) };
      case 'atk': { const k = atkK(t); return { x: 0.03 * k }; }
    }
  },
};

