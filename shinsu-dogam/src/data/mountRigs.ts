// 영물 원화 27장의 리그(부위·움직임) 정의. 좌표는 원화(오른쪽 방향) 폭·높이 대비 0..1.
// 부위 종류: leg(다리, 달리기 보행), wing(날개, 날갯짓 + 끝 깃털 지연), chain(꼬리·갈기·리본 물결),
//           head(고개), tassel(매듭·술 진자), sway(구름·뿔·장식 흔들림)
import type { BoneDef, RigDef, RigAnim, V, Pose, GlobalPose } from '../art/rig.ts';
import type { MotionKind } from './mountArt.ts';

const TAU = Math.PI * 2;
const sin = (t: number, ph = 0, f = 1) => Math.sin(TAU * (f * t + ph));
const flapK = (t: number, lag = 0) => (1 - Math.cos(TAU * (t - lag))) / 2; // 0 → 1(내려치기 끝) → 0
const atkK = (t: number) => Math.sin(Math.PI * Math.min(1, t * 1.3)); // 4프레임: 0, .9, .6, -
const R = (x0: number, y0: number, x1: number, y1: number): V[] => [[x0, y0], [x1, y0], [x1, y1], [x0, y1]];

type LegOpt = { ph: number; front: boolean; z?: number; amp?: number; style?: 'quad' | 'bird' | 'serpent' };
function leg(id: string, poly: V[], pivot: V, o: LegOpt): BoneDef {
  const st = o.style ?? 'quad';
  return {
    id, poly, pivot, z: o.z ?? 1, feather: 0.016,
    motion: (a: RigAnim, t: number): Pose => {
      switch (a) {
        case 'idle': return { r: 1.2 * sin(t, o.ph) };
        case 'run': return { r: (o.amp ?? (st === 'bird' ? 20 : 24)) * sin(t, o.ph), y: st === 'quad' ? -0.012 * Math.max(0, sin(t, o.ph + 0.25)) : 0 };
        case 'fly':
          if (st === 'quad') return { r: (o.front ? -26 : 24) + 5 * sin(t, o.ph) };
          return { r: (st === 'bird' ? 38 : 30) + 6 * sin(t, o.ph) }; // 날 때 다리를 뒤로 접음
        case 'atk': return { r: (o.front ? -30 : 8) * atkK(t) };
      }
    },
  };
}

type WingOpt = { dir: 1 | -1; D?: number; z?: number; tip?: { poly: V[]; pivot: V }; fill?: V[]; lag?: number };
function wing(id: string, poly: V[], pivot: V, o: WingOpt): BoneDef[] {
  const D = o.D ?? 48;
  const amp = (a: RigAnim) => (a === 'idle' ? 0.12 : a === 'run' ? 0.3 : 1);
  const lag0 = o.lag ?? 0;
  const out: BoneDef[] = [{
    id, poly, pivot, z: o.z ?? 1, feather: 0.014, fill: o.fill,
    motion: (a: RigAnim, t: number): Pose => {
      if (a === 'atk') { const k = atkK(t); return { r: o.dir * D * 0.85 * k, sy: 1 - 0.18 * k }; }
      const k = flapK(t, lag0) * amp(a);
      return { r: o.dir * D * k, sy: 1 - 0.24 * k };
    },
  }];
  if (o.tip) out.push({
    id: id + 'Tip', poly: o.tip.poly, pivot: o.tip.pivot, parent: id, z: o.z ?? 1, feather: 0.04,
    motion: (a: RigAnim, t: number): Pose => {
      if (a === 'atk') return { r: o.dir * D * 0.3 * atkK(t - 0.15) };
      // 끝 깃털은 한 박자 늦게 따라와 휘어짐 (올라갈 때 아래로, 내려갈 때 위로 젖힘)
      const k = (flapK(t, lag0 + 0.14) - flapK(t, lag0)) * amp(a);
      return { r: -o.dir * D * 0.45 * k + o.dir * D * 0.18 * flapK(t, lag0 + 0.1) * amp(a) };
    },
  });
  return out;
}

type ChainOpt = { amp?: number; runAmp?: number; flyAmp?: number; lag?: number; z?: number; parent?: string; fill?: V[]; f?: number };
function chain(id: string, poly: V[], path: V[], o: ChainOpt = {}): BoneDef {
  return {
    id, poly, path, z: o.z ?? 1, parent: o.parent, fill: o.fill, feather: 0.018,
    motion: (a: RigAnim, t: number, seg: number, segs: number): Pose => {
      const amp = a === 'idle' ? (o.amp ?? 6) : a === 'fly' ? (o.flyAmp ?? (o.amp ?? 6) * 2.2) : (o.runAmp ?? (o.amp ?? 6) * 1.6);
      const g = Math.pow((seg + 1) / segs, 0.7);
      return { r: amp * g * sin(t, -seg * (o.lag ?? 0.13), o.f ?? 1) };
    },
  };
}

function head(id: string, poly: V[], pivot: V): BoneDef {
  return {
    id, poly, pivot, z: 2, feather: 0.012,
    motion: (a: RigAnim, t: number): Pose => {
      switch (a) {
        case 'idle': return { r: 1.6 * sin(t, 0.2) };
        case 'run': return { r: 2.6 * sin(t, 0.1, 2) };
        case 'fly': return { r: -2 + 2 * sin(t, 0.3) };
        case 'atk': { const k = atkK(t); return { r: 9 * k, x: 0.035 * k }; }
      }
    },
  };
}

function tassel(id: string, poly: V[], pivot: V, z = 2): BoneDef {
  return {
    id, poly, pivot, z, feather: 0.015,
    motion: (a: RigAnim, t: number): Pose => {
      switch (a) {
        case 'idle': return { r: 5 * sin(t, 0.3) };
        case 'run': return { r: 6 + 13 * sin(t, 0.35, 1) };
        case 'fly': return { r: 14 + 9 * sin(t, 0.35) };
        case 'atk': return { r: -12 * atkK(t) };
      }
    },
  };
}

function sway(id: string, poly: V[], pivot: V, amp: number, o: { z?: number; parent?: string; ph?: number } = {}): BoneDef {
  return {
    id, poly, pivot, z: o.z ?? 1, parent: o.parent, feather: 0.018,
    motion: (a: RigAnim, t: number): Pose => ({ r: amp * (a === 'idle' ? 1 : a === 'fly' ? 2 : 1.5) * sin(t, o.ph ?? 0.15) }),
  };
}

