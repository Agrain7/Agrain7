import type { MountId } from './types.ts';

export type Speaker = 'haram' | 'narr' | 'boss' | MountId;
export interface Line {
  who: Speaker;
  text: string;
  /** 외침 (화면 흔들림) */
  shout?: boolean;
}
export interface StoryScene {
  id: string;
  /** 0 서장 · 1~6 장 · 7 종장 */
  chapter: number;
  /** 회상 목록에 보이는 이름 */
  label: string;
  /** 이 장면에 나오는 보스 (그림·이름) */
  bossId?: string;
  bossName?: string;
  lines: Line[];
}

