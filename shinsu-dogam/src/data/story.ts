const S = (id: string, chapter: number, label: string, lines: Line[], boss?: [string, string]): StoryScene =>
  ({ id, chapter, label, lines, ...(boss ? { bossId: boss[0], bossName: boss[1] } : {}) });
const n = (text: string): Line => ({ who: 'narr', text });
